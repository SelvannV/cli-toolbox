import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const SOURCE =
  "https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt";

const OUTPUT = resolve("src/data/words.ts");
const MIN_LENGTH = 5;
const MAX_LENGTH = 7;
const MAX_WORDS = 5_000;

async function main(): Promise<void> {
  console.log("Downloading frequency-ranked English words...");

  const response = await fetch(SOURCE);

  if (!response.ok) {
    throw new Error(
      `Download failed: ${response.status} ${response.statusText}`,
    );
  }

  const content = await response.text();

  const words = [
    ...new Set(
      content
        .split(/\r?\n/)
        .map((word) => word.trim().toLowerCase())
        .filter(
          (word) =>
            word.length >= MIN_LENGTH &&
            word.length <= MAX_LENGTH &&
            /^[a-z]+$/.test(word),
        ),
    ),
  ].slice(0, MAX_WORDS);

  if (words.length === 0) {
    throw new Error("No valid words found in the downloaded list.");
  }

  const output = [
    "// Generated by scripts/generate-words.ts",
    `// Source: ${SOURCE}`,
    `// ${words.length} frequency-ranked words (${MIN_LENGTH}-${MAX_LENGTH} letters).`,
    "",
    "export const WORDS = [",
    ...words.map((word) => `  ${JSON.stringify(word)},`),
    "] as const;",
    "",
  ].join("\n");

  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, output, "utf8");

  console.log(`Saved ${words.length} words to ${OUTPUT}`);
}

main().catch((error: unknown) => {
  console.error(
    "Failed to generate word list:",
    error instanceof Error ? error.message : error,
  );
  process.exitCode = 1;
});
